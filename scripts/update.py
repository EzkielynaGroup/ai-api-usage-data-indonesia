#!/usr/bin/env python3
"""Daily snapshot of Ezkielyna's public AI model usage, status and price files.

Fetches three public JSON files (no key, no secrets), removes model ids containing
uncensored/abliterated/nsfw, normalises the price list, and writes:

  data/YYYY/MM/DD/leaderboard.json   7-day usage ranking (CC BY 4.0)
  data/YYYY/MM/DD/models.json        per-model success rate, uptime, latency, speed
  data/YYYY/MM/DD/pricing.json       list prices per model (USD), public key groups only
  latest/*.json                      the same three files from the newest run
  README.md                          the block between the AUTO markers (top 10 table)

The date folder is the run date in Western Indonesia Time (WIB, UTC+7).
Only the Python standard library is used (3.9+).

Usage: python3 scripts/update.py [--root DIR] [--source URL] [--date YYYY-MM-DD]
"""
import argparse
import datetime as dt
import json
import os
import re
import sys
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request

SOURCE = "https://api.ezkielyna.store"
FILES = {
    "leaderboard": "/status/leaderboard.json",
    "models": "/status/models.json",
    "pricing": "/api/pricing",
}
BLOCKED = re.compile(r"uncensored|abliterated|nsfw", re.I)
WIB = dt.timezone(dt.timedelta(hours=7))
MAX_BYTES = 10 * 1024 * 1024
TIMEOUT_S = 30
USER_AGENT = "ai-api-usage-data-indonesia/1.0 (+https://github.com/EzkielynaGroup/ai-api-usage-data-indonesia)"
LICENSE = "CC BY 4.0"
ATTRIBUTION = "Data: Ezkielyna, CC BY 4.0 — https://ezkielyna.store/peringkat"
FALLBACK_PUBLIC_GROUPS = ["default", "free", "media", "premium", "pro"]
START = "<!-- AUTO:START (generated by scripts/update.py, do not edit by hand) -->"
END = "<!-- AUTO:END -->"
UTM = "?utm_source=github&utm_medium=readme&utm_campaign=ai-api-usage-data-indonesia"


class UpdateError(Exception):
    pass


# ---------- fetch ----------

def check_source(source):
    u = urllib.parse.urlparse(source)
    local = u.hostname in ("localhost", "127.0.0.1", "::1")
    if u.scheme != "https" and not (u.scheme == "http" and local):
        raise UpdateError("source must use https: %s" % source)
    return source.rstrip("/")


def fetch_json(url, attempts=2):
    last = None
    for i in range(attempts):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=TIMEOUT_S) as r:
                body = r.read(MAX_BYTES + 1)
            if len(body) > MAX_BYTES:
                raise UpdateError("%s is larger than %d bytes" % (url, MAX_BYTES))
            return json.loads(body.decode("utf-8"))
        except UpdateError:
            raise
        except (urllib.error.URLError, OSError, ValueError) as e:
            last = e
            if i + 1 < attempts:
                time.sleep(3)
    raise UpdateError("could not fetch %s: %s" % (url, last))


# ---------- normalise ----------

def keep(model_id):
    return isinstance(model_id, str) and not BLOCKED.search(model_id)


def norm_leaderboard(v, source):
    items = (v.get("models") or {}).get("items")
    if not isinstance(items, list):
        raise UpdateError("leaderboard.json has no models.items list")
    out = {
        "source_url": source + FILES["leaderboard"],
        "license": LICENSE,
        "attribution": ATTRIBUTION,
        "schema": v.get("schema"),
        "generated_at": v.get("generated_at"),
        "window": v.get("window"),
        "models": {k: x for k, x in v["models"].items() if k != "items"},
    }
    out["models"]["items"] = [{k: x for k, x in i.items() if k != "icon"} for i in items if isinstance(i, dict) and keep(i.get("model"))]
    apps = v.get("apps")
    if isinstance(apps, dict):
        out["apps"] = dict(apps)
        out["apps"]["items"] = [a for a in apps.get("items") or [] if isinstance(a, dict)]
    return out


def norm_models(v, source):
    models = v.get("models")
    if not isinstance(models, dict):
        raise UpdateError("models.json has no models object")
    return {
        "source_url": source + FILES["models"],
        "license": LICENSE,
        "schema": v.get("schema"),
        "generated_at": v.get("generated_at"),
        "notes": v.get("notes"),
        "models": {k: models[k] for k in sorted(models) if keep(k) and isinstance(models[k], dict)},
    }


def _num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return 0.0


def _round(x):
    return None if x is None else float("%.6g" % x)


def norm_pricing(v, source):
    rows = v.get("data")
    if not isinstance(rows, list):
        raise UpdateError("pricing has no data list")
    ratio = v.get("group_ratio") if isinstance(v.get("group_ratio"), dict) else {}
    labels = v.get("usable_group") if isinstance(v.get("usable_group"), dict) else {}
    public = [g for g in labels if g != "auto" and _num(ratio.get(g)) > 0] or [g for g in FALLBACK_PUBLIC_GROUPS if _num(ratio.get(g)) > 0]
    vendors = {x.get("id"): x.get("name") for x in v.get("vendors") or [] if isinstance(x, dict)}
    groups = {g: {"label": str(labels.get(g, g)), "multiplier": _num(ratio.get(g))} for g in public}
    models = []
    for m in rows:
        if not isinstance(m, dict) or not keep(m.get("model_name")):
            continue
        gs = [g for g in m.get("enable_groups") or [] if g in public]
        if not gs:
            continue  # not sold in a public key group
        mult = min(_num(ratio[g]) for g in gs)
        tags = str(m.get("tags") or "")
        ep = [e for e in m.get("supported_endpoint_types") or [] if isinstance(e, str)]
        desc = str(m.get("description") or "")
        row = {
            "id": m["model_name"],
            "vendor": vendors.get(m.get("vendor_id")),
            "key_groups": sorted(gs),
            "multiplier": mult,
            "tags": tags or None,
            "endpoints": sorted(ep),
        }
        if int(_num(m.get("quota_type"))) == 1:
            unit = re.search(r"priced per (image|second|request|minute|call)", desc, re.I)
            row["billing"] = "per_call"
            row["unit"] = unit.group(1).lower() if unit else "call"
            row["price_usd"] = _round(_num(m.get("model_price")) * mult) if _num(m.get("model_price")) > 0 else None
        else:
            r = _num(m.get("model_ratio"))
            inp = r * 2 * mult if r > 0 else None
            comp = _num(m.get("completion_ratio")) or 1.0
            cache = _num(m.get("cache_ratio"))
            is_tts = tags.lower() == "tts" or ("openai-audio" in ep and tags.lower() != "stt")
            is_stt = tags.lower() == "stt" or re.match(r"(stt-|whisper)", m["model_name"], re.I) is not None
            row["billing"] = "characters" if is_tts and not is_stt else "audio_minutes" if is_stt else "tokens"
            row["input_usd_per_1m"] = _round(inp)
            row["output_usd_per_1m"] = _round(inp * comp) if inp is not None else None
            row["cached_input_usd_per_1m"] = _round(inp * cache) if inp is not None and 0 < cache < 1 else None
        models.append(row)
    models.sort(key=lambda x: x["id"])
    return {
        "source_url": source + FILES["pricing"],
        "license": LICENSE,
        "pricing_version": v.get("pricing_version"),
        "price_rule": "tokens: input = model_ratio x $2 per 1M, output = input x completion_ratio; per_call: model_price; "
                      "both x the lowest public key-group multiplier the model is in. characters = per 1M input characters (speech). "
                      "audio_minutes: billed by audio length, the per-1M figure is the raw rate.",
        "groups": groups,
        "models": models,
    }


# ---------- README block ----------

def _fmt_int(n):
    return "{:,}".format(int(n)) if n is not None else "-"


def _pct(n):
    return "-" if n is None else ("%g%%" % round(float(n), 2))


def _when(ts):
    ts = str(ts or "")
    if ts.endswith("+07:00"):
        return ts[:16].replace("T", " ") + " WIB"
    return ts or "unknown time"


def readme_block(lb, st):
    items = lb["models"]["items"]
    w = lb.get("window") or {}
    start, end = str(w.get("start", ""))[:10], str(w.get("end", ""))[:10]
    status = st["models"]
    lines = [
        START,
        "",
        "**Top 10 models this week on Ezkielyna** (%s to %s, by requests; uptime = 7 days). Snapshot of %s." % (start, end, _when(lb.get("generated_at"))),
        "",
        "| # | Model | Vendor | Share of requests | Requests | Users | vs last week | Uptime 7d |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i in items[:10]:
        if i.get("is_new") or i.get("rank_prev") is None:
            change = "new"
        else:
            c = i.get("change_pct")
            change = ("%+g%%" % c) if c is not None else "-"
            if i.get("rank_prev") != i.get("rank"):
                change += " (was #%s)" % i.get("rank_prev")
        up = (status.get(i["model"]) or {}).get("uptime_7d")
        lines.append("| %s | `%s` | %s | %s | %s | %s | %s | %s |" % (
            i.get("rank"), i["model"], i.get("vendor") or "-", _pct(i.get("share_pct")), _fmt_int(i.get("requests")),
            _fmt_int(i.get("users")), change, _pct(up)))
    if items:
        top = items[0]
        by_vendor = {}
        for i in items:
            by_vendor[i.get("vendor") or "?"] = by_vendor.get(i.get("vendor") or "?", 0) + (i.get("share_pct") or 0)
        lead_vendor, lead_share = max(by_vendor.items(), key=lambda kv: kv[1])
        lines += [
            "",
            "This week the most-used model was `%s` (%s of requests). Models from %s together took %s of requests. "
            "Shares are as published by the gateway; only models used by at least %s people in the week are listed." % (top["model"], _pct(top.get("share_pct")), lead_vendor, _pct(lead_share),
                                                                   lb["models"].get("min_users", 3)),
            "",
            "Minggu ini model yang paling banyak dipakai adalah `%s` (%s dari request); model buatan %s bersama-sama %s."
            % (top["model"], _pct(top.get("share_pct")).replace(".", ","), lead_vendor, _pct(lead_share).replace(".", ",")),
        ]
    lines += ["", ATTRIBUTION, "", END]
    return "\n".join(lines)


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def update_readme(path, block):
    text = read_text(path) if os.path.exists(path) else ""
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        new = head + block + tail
    else:
        new = (text.rstrip("\n") + "\n\n" if text else "") + block + "\n"
    return write_if_changed(path, new)


# ---------- write ----------

def dump(v):
    return json.dumps(v, ensure_ascii=False, indent=1, sort_keys=False) + "\n"


def write_if_changed(path, content):
    if os.path.exists(path) and read_text(path) == content:
        return False
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path) or ".", prefix=".tmp-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(content)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)
    return True


def run(root, source=SOURCE, date=None):
    source = check_source(source)
    raw = {k: fetch_json(source + p) for k, p in FILES.items()}  # fetch everything before writing anything
    out = {
        "leaderboard": norm_leaderboard(raw["leaderboard"], source),
        "models": norm_models(raw["models"], source),
        "pricing": norm_pricing(raw["pricing"], source),
    }
    day = date or dt.datetime.now(WIB).date().isoformat()
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", day):
        raise UpdateError("date must be YYYY-MM-DD")
    y, m, d = day.split("-")
    changed = []
    for name, v in out.items():
        body = dump(v)
        for p in (os.path.join(root, "data", y, m, d, name + ".json"), os.path.join(root, "latest", name + ".json")):
            if write_if_changed(p, body):
                changed.append(os.path.relpath(p, root))
    if update_readme(os.path.join(root, "README.md"), readme_block(out["leaderboard"], out["models"])):
        changed.append("README.md")
    return day, changed


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))), help="repo folder")
    ap.add_argument("--source", default=SOURCE, help="data origin (https)")
    ap.add_argument("--date", default=None, help="snapshot date YYYY-MM-DD (default: today in WIB)")
    a = ap.parse_args(argv)
    try:
        day, changed = run(a.root, a.source, a.date)
    except UpdateError as e:
        print("update failed: %s" % e, file=sys.stderr)
        return 1
    print("snapshot %s: %s" % (day, ", ".join(changed) if changed else "no change"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
